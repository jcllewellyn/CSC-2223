#include <stdio.h>

int main() {

	/*
	 Characters or char:
	 - Single Character
	 - Ascii Characters
	 - Literals are integers or use single quote 'a'
	 - chars are 9 bits, or 1 byte
	 */

	char letter = 'A';

	printf("letter (as char) = %c \n", letter);
	printf("letter (as digit) = %d \n", letter);

	return 0;
}
